def st(cols, rows, obj_name, obj, pivot=None, cap=""):
    """Сокращённая симплекс-таблица. rows: [(базисная, [значения..., b])]."""
    pr, pc = pivot if pivot else (None, None)
    h = "<tr><th></th>" + "".join(
        f'<th class="{"colsel" if j == pc else ""}">${c}$</th>' for j, c in enumerate(cols)) + "<th>$b$</th></tr>"
    body = ""
    for i, (name, vals) in enumerate(rows):
        tds = ""
        for j, v in enumerate(vals):
            cls = "pv" if (i == pr and j == pc) else ("rowsel" if i == pr else ("colsel" if j == pc else ""))
            tds += f'<td class="{cls}">${v}$</td>'
        body += f'<tr><th class="{"rowsel" if i == pr else ""}">${name}$</th>{tds}</tr>'
    body += f'<tr class="obj"><th>${obj_name}$</th>' + "".join(
        f'<td class="{"colsel" if j == pc else ""}">${v}$</td>' for j, v in enumerate(obj)) + "</tr>"
    c = f'<div class="cap">{cap}</div>' if cap else ""
    return f'<div>{c}<table class="st">{h}{body}</table></div>'


def f(s):
    """'-1/2' -> '-\\frac12' для KaTeX."""
    s = str(s)
    if "/" in s:
        neg = s.startswith("-")
        a, b = s.lstrip("-").split("/")
        return ("-" if neg else "") + f"\\tfrac{{{a}}}{{{b}}}"
    return s


def F(lst):
    return [f(v) for v in lst]


